def is_function_called_in_messages(messages: List[Dict[str, Any]], function_name: str) -> bool:
    """Check if a function was called in the messages.

    Supports two formats:
    1. Claude native format: content is list with {"type": "tool_use", "name": "...", ...}
    2. Text-based format (Qwen/vLLM/GPT): JSON block in content string
    """
    for msg in messages:
        if msg.get("role") == "assistant":
            content = msg.get("content", "")

            # Check Claude format (content is a list with tool_use)
            if isinstance(content, list):
                _, tool_use = _parse_claude_content(content)
                if tool_use and tool_use.get("name") == function_name:
                    return True
                continue

            # Check text-based format
            if isinstance(content, str):
                text_tool_call = _parse_text_tool_call(content)
                if text_tool_call and text_tool_call.get("name") == function_name:
                    return True
    return False


def get_all_called_functions(messages: List[Dict[str, Any]]) -> List[str]:
    """Get all functions called in the messages.

    Supports three formats:
    1. Claude native format: content is list with {"type": "tool_use", "name": "...", ...}
    2. OpenAI native FC (kimi/gpt5/grok/gemini/vllm_serve_fc): assistant msg has
       tool_calls=[{"function": {"name": "..."}}] alongside content.
    3. Text-based format (Qwen/vLLM/openai text-fence): JSON block in content string.
    """
    functions = []
    for msg in messages:
        if msg.get("role") != "assistant":
            continue
        content = msg.get("content", "")

        # OpenAI native FC: tool_calls list takes precedence; the assistant
        # message may also have a non-empty 'content' (the model's reasoning),
        # so check tool_calls FIRST and skip the fence parser if present.
        tool_calls = msg.get("tool_calls") or []
        if tool_calls:
            for tc in tool_calls:
                fn = (tc.get("function") or {}).get("name")
                if fn:
                    functions.append(fn)
            continue

        # Claude format (content is a list with tool_use blocks)
        if isinstance(content, list):
            _, tool_use = _parse_claude_content(content)
            if tool_use and tool_use.get("name"):
                functions.append(tool_use["name"])
            continue

        # Text-fence ReAct format (```json{"name":..., "arguments":...}```)
        if isinstance(content, str):
            text_tool_call = _parse_text_tool_call(content)
            if text_tool_call and text_tool_call.get("name"):
                functions.append(text_tool_call["name"])
    return functions
