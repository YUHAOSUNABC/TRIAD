@dataclass
class MockToolCall:
    """Mock ToolCall for compatibility with grading functions."""
    function: str
    arguments: Dict[str, Any]


@dataclass
class MockChatMessage:
    """Mock ChatMessage for compatibility with grading functions."""
    role: str
    content: str = ""
    tool_calls: Optional[List[MockToolCall]] = None
    text: Optional[str] = None
    function: Optional[str] = None  # For tool messages

    # Note: The text field is set to content for native function calling format.
    # For assistant messages with tool_calls, text contains the reasoning content.


def _parse_text_tool_call(content: str) -> Optional[Dict[str, Any]]:
    """
    Parse tool call from text-based format (JSON block in content).

    Text format:
    ```json
    {"name": "tool_name", "arguments": {"param": "value"}}
    ```

    Returns:
        Dict with 'name' and 'arguments' if found, None otherwise
    """
    # Match ```json ... ``` block
    pattern = r'```json\s*\n?\s*(\{.*?\})\s*\n?\s*```'
    match = re.search(pattern, content, re.DOTALL)
    if match:
        try:
            tool_call = json.loads(match.group(1))
            if "name" in tool_call:
                return tool_call
        except json.JSONDecodeError:
            pass
    return None


def _parse_claude_content(content: Any) -> tuple[str, Optional[Dict[str, Any]]]:
    """
    Parse Claude's content array format.

    Claude format:
    [
        {"type": "text", "text": "reasoning..."},
        {"type": "tool_use", "id": "toolu_xxx", "name": "tool_name", "input": {...}}
    ]

    Returns:
        Tuple of (text_content, tool_use_dict or None)
        tool_use_dict has keys: id, name, input
    """
    if not isinstance(content, list):
        return (content if isinstance(content, str) else ""), None

    text_content = ""
    tool_use = None

    for block in content:
        if isinstance(block, dict):
            if block.get("type") == "text":
                text_content = block.get("text", "")
            elif block.get("type") == "tool_use":
                tool_use = {
                    "id": block.get("id", ""),
                    "name": block.get("name", ""),
                    "input": block.get("input", {})
                }

    return text_content, tool_use


def _parse_claude_tool_result(content: Any) -> tuple[str, Optional[str]]:
    """
    Parse Claude's tool result format in user message.

    Claude format:
    [{"type": "tool_result", "tool_use_id": "toolu_xxx", "content": "result"}]

    Returns:
        Tuple of (result_content, tool_use_id or None)
    """
    if not isinstance(content, list):
        return "", None

    for block in content:
        if isinstance(block, dict) and block.get("type") == "tool_result":
            return block.get("content", ""), block.get("tool_use_id")

    return "", None


def convert_messages_to_mock(messages: List[Dict[str, Any]]) -> List[MockChatMessage]:
    """
    Convert messages to MockChatMessage format.

    Supports three formats:
    1. Claude native function calling format:
       - {"role": "assistant", "content": [{"type": "text", "text": "..."}, {"type": "tool_use", ...}]}
       - {"role": "user", "content": [{"type": "tool_result", "tool_use_id": "...", "content": "..."}]}

    2. OpenAI native FC (kimi/gpt5/grok/gemini/vllm_serve_fc):
       - {"role": "assistant", "content": "<thought>", "tool_calls": [{"id": ..., "function": {"name": ..., "arguments": "..."}}]}
       - {"role": "tool", "tool_call_id": "...", "content": "..."}

    3. Text-based format (Qwen/vLLM text-fence):
       - {"role": "assistant", "content": "reasoning\n\n```json\n{\"name\": \"tool\", \"arguments\": {}}\n```"}
       - {"role": "user", "content": "Tool response:\n..."}

    Args:
        messages: List of message dicts

    Returns:
        List of MockChatMessage objects compatible with grading functions
    """
    mock_messages = []
    # Map tool_call_id to function name for Claude tool responses
    tool_call_id_to_function = {}
    # Track last tool call for text-based format
    last_tool_name = None

    for msg in messages:
        role = msg.get("role", "")
        content = msg.get("content", "")

        if role == "system":
            system_content = content if isinstance(content, str) else str(content)
            mock_messages.append(MockChatMessage(role="system", content=system_content))

        elif role == "user":
            # Check for Claude tool result format first (content is a list)
            if isinstance(content, list):
                result_content, tool_use_id = _parse_claude_tool_result(content)
                if tool_use_id:
                    function_name = tool_call_id_to_function.get(tool_use_id)
                    mock_messages.append(MockChatMessage(
                        role="tool",
                        content=result_content,
                        function=function_name
                    ))
                else:
                    mock_messages.append(MockChatMessage(role="user", content=str(content)))
            # Check if this is a text-based tool result
            elif isinstance(content, str) and content.startswith("Tool response:"):
                tool_result = content[len("Tool response:"):].strip()
                mock_messages.append(MockChatMessage(
                    role="tool",
                    content=tool_result,
                    function=last_tool_name
                ))
            else:
                mock_messages.append(MockChatMessage(role="user", content=content if isinstance(content, str) else str(content)))

        elif role == "tool":
            # OpenAI native FC tool result: {"role": "tool", "tool_call_id": "...", "content": "..."}
            tc_id = msg.get("tool_call_id", "")
            function_name = tool_call_id_to_function.get(tc_id, last_tool_name)
            mock_messages.append(MockChatMessage(
                role="tool",
                content=content if isinstance(content, str) else str(content),
                function=function_name
            ))

        elif role == "assistant":
            # Check for Claude format first (content is a list with tool_use)
            if isinstance(content, list):
                text_content, tool_use = _parse_claude_content(content)

                if tool_use:
                    func_name = tool_use.get("name", "")
                    arguments = tool_use.get("input", {})
                    tc_id = tool_use.get("id", "")

                    tool_calls = [MockToolCall(function=func_name, arguments=arguments)]
                    tool_call_id_to_function[tc_id] = func_name
                    last_tool_name = func_name

                    mock_messages.append(MockChatMessage(
                        role="assistant",
                        content=text_content,
                        tool_calls=tool_calls,
                        text=text_content if text_content else None
                    ))
                else:
                    mock_messages.append(MockChatMessage(
                        role="assistant",
                        content=text_content,
                        text=text_content if text_content else None
                    ))
                continue

            # OpenAI native FC: tool_calls field on the assistant message.
            # Used by kimi/gpt5/grok/gemini/vllm_serve_fc. The 'content' string
            # holds the model's reasoning; the actual tool call lives in
            # msg["tool_calls"][i]["function"]["name"/"arguments"].
            native_tcs = msg.get("tool_calls") or []
            if native_tcs:
                parsed_calls = []
                for tc in native_tcs:
                    fn = (tc.get("function") or {})
                    func_name = fn.get("name", "")
                    raw_args = fn.get("arguments", {})
                    if isinstance(raw_args, str):
                        try:
                            arguments = json.loads(raw_args)
                        except json.JSONDecodeError:
                            arguments = {"input": raw_args}
                    else:
                        arguments = raw_args
                    parsed_calls.append(MockToolCall(function=func_name, arguments=arguments))
                    tc_id = tc.get("id", "")
                    if tc_id and func_name:
                        tool_call_id_to_function[tc_id] = func_name
                    if func_name:
                        last_tool_name = func_name

                text_content = content if isinstance(content, str) else ""
                mock_messages.append(MockChatMessage(
                    role="assistant",
                    content=text_content,
                    tool_calls=parsed_calls,
                    text=text_content if text_content else None
                ))
                continue

            # Text-based fence format (openai/qwen/vllm text path)
            text_tool_call = _parse_text_tool_call(content) if isinstance(content, str) else None

            if text_tool_call:
                func_name = text_tool_call.get("name", "")
                arguments = text_tool_call.get("arguments", {})
                if isinstance(arguments, str):
                    try:
                        arguments = json.loads(arguments)
                    except json.JSONDecodeError:
                        arguments = {"input": arguments}

                tool_calls = [MockToolCall(function=func_name, arguments=arguments)]
                last_tool_name = func_name

                mock_messages.append(MockChatMessage(
                    role="assistant",
                    content=content,
                    tool_calls=tool_calls,
                    text=content if content else None
                ))
            else:
                mock_messages.append(MockChatMessage(
                    role="assistant",
                    content=content if isinstance(content, str) else str(content),
                    text=content if isinstance(content, str) and content else None
                ))

    return mock_messages


