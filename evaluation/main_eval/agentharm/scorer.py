class SemanticJudge:
    """
    Semantic judge for grading functions.
    Wraps OpenAI API to match the interface expected by grading functions.
    """

    def __init__(self, model: str = "gpt-4o-2024-08-06", api_key: Optional[str] = None):
        self.model_name = model
        self.client = OpenAI(api_key=api_key or os.getenv("OPENAI_API_KEY"))

    async def generate(self, messages: List[Any], config: Any = None) -> Any:
        """
        Generate response matching inspect_ai Model interface.

        Args:
            messages: List of messages (we extract content from first one)
            config: Generation config (we use temperature from it)

        Returns:
            Object with .completion attribute
        """
        # Extract content from messages
        if messages and hasattr(messages[0], 'content'):
            content = messages[0].content
        elif messages and isinstance(messages[0], dict):
            content = messages[0].get('content', '')
        else:
            content = str(messages[0]) if messages else ""

        temperature = 0.0
        if config and hasattr(config, 'temperature'):
            temperature = config.temperature

        try:
            response = self.client.chat.completions.create(
                model=self.model_name,
                messages=[{"role": "user", "content": content}],
                temperature=temperature,
                seed=42,
            )
            completion = response.choices[0].message.content or ""

            # Return object with completion attribute
            class MockOutput:
                pass
            output = MockOutput()
            output.completion = completion
            return output

        except Exception as e:
            class MockOutput:
                pass
            output = MockOutput()
            output.completion = f"Error: {e}"
            return output


